use crate::{
    config::{CONFIG_FILE_NAME, ProjectConfig},
    registry::Registry,
};
use colored::Colorize;
use inquire::Text;
use std::{fs, path::Path};

#[derive(Debug, PartialEq, Eq)]
enum InitOutcome {
    AlreadyExists,
    Initialized { core_installed: bool },
}

#[allow(clippy::too_many_lines)]
pub fn execute() -> Result<(), Box<dyn std::error::Error>> {
    println!("{}", "Initializing iu_ui project...".cyan().bold());

    if Path::new(CONFIG_FILE_NAME).exists() {
        println!("{}", "[Warning] `iu_ui.toml` already exists.".yellow());
        return Ok(());
    }

    // 対話プロンプトでベースパスを確認
    let default_base = "src/iu_ui";
    let base_dir = Text::new("Where should iu_ui components be installed?")
        .with_default(default_base)
        .with_help_message("Press <Enter> to accept default (src/iu_ui)")
        .prompt()?;

    let default_repo = "eto0202/michiu";
    let repo = Text::new("GitHub repository:")
        .with_default(default_repo)
        .with_help_message("Press <Enter> to accept default repository")
        .prompt()?;
    let branch = "main";

    init_project(
        Path::new("."),
        &base_dir,
        &repo,
        branch,
        Registry::fetch_raw_file,
    )?;

    println!("{}", "\nSuccessfully initialized iu_ui!".green().bold());
    println!("Created:");
    println!("  - {}", CONFIG_FILE_NAME.bold());
    println!("  - {}/core.rs (Core traits & types)", base_dir.bold());
    println!("  - {}/mod.rs", base_dir.bold());
    println!("\nNext steps:");
    println!(
        "  1. Add `mod iu_ui;` to your {} or {}",
        "src/main.rs".cyan(),
        "src/lib.rs".cyan()
    );
    println!("  2. Run {} to browse catalog", "cargo iu_ui list".cyan());
    println!(
        "  3. Run {} to add your first component",
        "cargo iu_ui add simple_button".cyan()
    );

    Ok(())
}

fn build_project_config(base_dir: &str) -> ProjectConfig {
    ProjectConfig {
        base_dir: base_dir.to_string(),
        components_dir: format!("{base_dir}/components"),
        theme_dir: format!("{base_dir}/theme"),
        tag_dir: format!("{base_dir}/tag"),
        utils_dir: format!("{base_dir}/utils"),
        assets_dir: format!("{base_dir}/assets"),
    }
}

fn init_project<F>(
    root: &Path,
    base_dir: &str,
    repo: &str,
    branch: &str,
    fetch_core: F,
) -> Result<InitOutcome, Box<dyn std::error::Error>>
where
    F: FnOnce(&str, &str, &str) -> Result<String, Box<dyn std::error::Error>>,
{
    let config_path = root.join(CONFIG_FILE_NAME);
    if config_path.exists() {
        return Ok(InitOutcome::AlreadyExists);
    }

    let project = build_project_config(base_dir);

    println!("Creating directories...");
    fs::create_dir_all(root.join(&project.base_dir))?;
    fs::create_dir_all(root.join(&project.components_dir))?;
    fs::create_dir_all(root.join(&project.theme_dir))?;
    fs::create_dir_all(root.join(&project.tag_dir))?;
    fs::create_dir_all(root.join(&project.utils_dir))?;
    fs::create_dir_all(root.join(&project.assets_dir))?;

    // core.rs の自動ダウンロード
    println!("↓ Downloading core.rs...");
    let core_remote_path = "iu_ui/src/core.rs";
    let core_installed = match fetch_core(repo, branch, core_remote_path) {
        Ok(core_content) => {
            let core_dest = root.join(&project.base_dir).join("core.rs");
            fs::write(core_dest, core_content)?;
            println!("  {} Installed core.rs.", "[Success]".green());
            true
        }
        Err(e) => {
            eprintln!("  {} Failed to fetch core.rs: {}", "[Warning]".yellow(), e);
            false
        }
    };

    // base_dir 直下に mod.rs を作成
    let base_mod = root.join(&project.base_dir).join("mod.rs");
    if !base_mod.exists() {
        let base_mod_content = r"// Generated by iu_ui
// Please include `mod iu_ui;` in `main.rs` or `lib.rs` to use it.
pub mod core;
pub mod components;
pub mod theme;
pub mod tag;
pub mod utils;

pub mod prelude {
    pub use super::core::*;
    pub use super::theme::*;
    pub use super::components::*;
}
";
        fs::write(&base_mod, base_mod_content)?;
    }

    // components/mod.rs などの空ファイルを初期化
    let sub_mods = [
        (
            &project.components_dir,
            "// Managed by iu_ui (components)\npub(crate) use super::core;\n",
        ),
        (
            &project.theme_dir,
            "// Managed by iu_ui (themes)\npub(crate) use super::core;\n",
        ),
        (
            &project.tag_dir,
            "// Managed by iu_ui (tags)\npub(crate) use super::core;\n",
        ),
        (
            &project.utils_dir,
            "// Managed by iu_ui (utils)\npub(crate) use super::core;\n",
        ),
    ];

    for (dir, comment) in sub_mods {
        let mod_file = root.join(dir).join("mod.rs");
        if !mod_file.exists() {
            fs::write(&mod_file, comment)?;
        }
    }

    generate_initial_setting_toml_to(&config_path, &project, repo, branch)?;

    Ok(InitOutcome::Initialized { core_installed })
}

fn build_initial_setting_toml(project: &ProjectConfig, repo: &str, branch: &str) -> String {
    format!(
        r#"# ==============================================================================
# iu_ui Configuration File
#
# This configuration file is automatically managed by `cargo iu_ui`.
# You can edit this file directly to modify directory paths or the repository.
# ==============================================================================

[project]
# Base directory for iu_ui, referenced from main.rs via `mod iu_ui;`.
base_dir = "{base_dir}"

# Directory for UI components (single-file or folder modules).
components_dir = "{components_dir}"

# Directory for color themes meeting contrast ratios like WCAG AA.
theme_dir = "{theme_dir}"

# Directory for accessibility inference tags (A11yInferenceTag implementations).
tag_dir = "{tag_dir}"

# Directory for shared helper functions and calculation utilities.
utils_dir = "{utils_dir}"

# Directory for static assets such as SVG icons, images, and cursor files.
assets_dir = "{assets_dir}"

[registry]
# GitHub repository to fetch the catalog from (owner/repo).
repo = "{repo}"

# Branch to reference (usually main).
branch = "{branch}"

# ------------------------------------------------------------------------------
# Version tracking for installed components.
# Automatically updated and maintained by `cargo iu_ui add` and `cargo iu_ui check`.
# ------------------------------------------------------------------------------

[installed.components]

[installed.themes]

[installed.tags]

[installed.utils]

# Shared asset usage (for deduplication and sharing across multiple components).
[installed.assets]
"#,
        base_dir = project.base_dir,
        components_dir = project.components_dir,
        theme_dir = project.theme_dir,
        tag_dir = project.tag_dir,
        utils_dir = project.utils_dir,
        assets_dir = project.assets_dir,
        repo = repo,
        branch = branch,
    )
}

fn generate_initial_setting_toml_to(
    path: &Path,
    project: &ProjectConfig,
    repo: &str,
    branch: &str,
) -> Result<(), std::io::Error> {
    let toml_content = build_initial_setting_toml(project, repo, branch);
    fs::write(path, toml_content)
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::config::{RegistryConfig, Setting};
    use std::{
        path::PathBuf,
        sync::atomic::{AtomicUsize, Ordering},
    };

    struct TestDir {
        path: PathBuf,
    }

    impl TestDir {
        fn new(prefix: &str) -> Self {
            static COUNTER: AtomicUsize = AtomicUsize::new(0);
            let id = COUNTER.fetch_add(1, Ordering::Relaxed);
            let pid = std::process::id();
            let path = std::env::temp_dir().join(format!("iu_ui_init_test_{prefix}_{pid}_{id}"));
            if path.exists() {
                let _ = fs::remove_dir_all(&path);
            }
            fs::create_dir_all(&path).expect("failed to create test dir");
            Self { path }
        }

        fn path(&self) -> &Path {
            &self.path
        }
    }

    impl Drop for TestDir {
        fn drop(&mut self) {
            let _ = fs::remove_dir_all(&self.path);
        }
    }

    #[test]
    fn test_build_project_config() {
        let cfg = build_project_config("src/custom_ui");
        assert_eq!(cfg.base_dir, "src/custom_ui");
        assert_eq!(cfg.components_dir, "src/custom_ui/components");
        assert_eq!(cfg.theme_dir, "src/custom_ui/theme");
        assert_eq!(cfg.tag_dir, "src/custom_ui/tag");
        assert_eq!(cfg.utils_dir, "src/custom_ui/utils");
        assert_eq!(cfg.assets_dir, "src/custom_ui/assets");
    }

    #[test]
    fn test_build_initial_setting_toml_is_valid_setting() {
        let project = build_project_config("src/iu_ui");
        let toml_str = build_initial_setting_toml(&project, "eto0202/michiu", "main");

        let parsed: Setting = toml::from_str(&toml_str).unwrap();
        assert_eq!(parsed.project, project);
        assert_eq!(
            parsed.registry,
            RegistryConfig {
                repo: "eto0202/michiu".to_string(),
                branch: "main".to_string(),
            }
        );
        assert!(parsed.installed.components.is_empty());
        assert!(parsed.installed.themes.is_empty());
        assert!(parsed.installed.tags.is_empty());
        assert!(parsed.installed.utils.is_empty());
        assert!(parsed.installed.assets.is_empty());
    }

    #[test]
    fn test_init_project_skips_when_config_already_exists() {
        let dir = TestDir::new("exists");
        let root = dir.path();
        let config_path = root.join(CONFIG_FILE_NAME);
        fs::write(&config_path, "# existing config").unwrap();

        let mut fetch_called = false;
        let outcome = init_project(root, "src/iu_ui", "eto0202/michiu", "main", |_, _, _| {
            fetch_called = true;
            Ok("pub trait Core {}".to_string())
        })
        .unwrap();

        assert_eq!(outcome, InitOutcome::AlreadyExists);
        assert!(!fetch_called);
        // 既存ファイルが上書きされていないこと
        assert_eq!(
            fs::read_to_string(&config_path).unwrap(),
            "# existing config"
        );
        assert!(!root.join("src/iu_ui").exists());
    }

    #[test]
    fn test_init_project_success_with_core_download() {
        let dir = TestDir::new("success");
        let root = dir.path();

        let outcome = init_project(
            root,
            "src/iu_ui",
            "my_org/my_repo",
            "main",
            |repo, branch, path| {
                assert_eq!(repo, "my_org/my_repo");
                assert_eq!(branch, "main");
                assert_eq!(path, "iu_ui/src/core.rs");
                Ok("pub struct CoreStub;".to_string())
            },
        )
        .unwrap();

        assert_eq!(
            outcome,
            InitOutcome::Initialized {
                core_installed: true
            }
        );

        // 全ディレクトリ作成確認
        for rel in [
            "src/iu_ui",
            "src/iu_ui/components",
            "src/iu_ui/theme",
            "src/iu_ui/tag",
            "src/iu_ui/utils",
            "src/iu_ui/assets",
        ] {
            assert!(root.join(rel).is_dir(), "{rel} should be created");
        }

        // core.rs 確認
        assert_eq!(
            fs::read_to_string(root.join("src/iu_ui/core.rs")).unwrap(),
            "pub struct CoreStub;"
        );

        // base mod.rs & サブ mod.rs 確認
        let base_mod = fs::read_to_string(root.join("src/iu_ui/mod.rs")).unwrap();
        assert!(base_mod.contains("pub mod core;"));
        assert!(base_mod.contains("pub mod prelude"));

        for sub in ["components", "theme", "tag", "utils"] {
            let sub_mod = fs::read_to_string(root.join(format!("src/iu_ui/{sub}/mod.rs"))).unwrap();
            assert!(sub_mod.contains("pub(crate) use super::core;"));
        }

        // 生成された iu_ui.toml が Setting::load_from で読めること
        let setting = Setting::load_from(&root.join(CONFIG_FILE_NAME)).unwrap();
        assert_eq!(setting.project.base_dir, "src/iu_ui");
        assert_eq!(setting.registry.repo, "my_org/my_repo");
        assert_eq!(setting.registry.branch, "main");
    }

    #[test]
    fn test_init_project_continues_when_core_fetch_fails() {
        let dir = TestDir::new("fetch_fail");
        let root = dir.path();

        let outcome = init_project(root, "src/ui", "eto0202/michiu", "main", |_, _, _| {
            Err("network error".into())
        })
        .unwrap();

        // エラーにせず続行し、core_installed が false になること
        assert_eq!(
            outcome,
            InitOutcome::Initialized {
                core_installed: false
            }
        );
        assert!(!root.join("src/ui/core.rs").exists());
        assert!(root.join("src/ui/mod.rs").exists());
        assert!(root.join("src/ui/components/mod.rs").exists());
        assert!(root.join(CONFIG_FILE_NAME).exists());
    }

    #[test]
    fn test_init_project_preserves_existing_mod_files() {
        let dir = TestDir::new("preserve_mod");
        let root = dir.path();

        fs::create_dir_all(root.join("src/iu_ui/components")).unwrap();
        fs::write(root.join("src/iu_ui/mod.rs"), "// custom root mod").unwrap();
        fs::write(
            root.join("src/iu_ui/components/mod.rs"),
            "// custom comp mod",
        )
        .unwrap();

        init_project(root, "src/iu_ui", "eto0202/michiu", "main", |_, _, _| {
            Ok("// core".to_string())
        })
        .unwrap();

        // 既存の mod.rs は上書きされず、存在しなかった theme/mod.rs 等は作られること
        assert_eq!(
            fs::read_to_string(root.join("src/iu_ui/mod.rs")).unwrap(),
            "// custom root mod"
        );
        assert_eq!(
            fs::read_to_string(root.join("src/iu_ui/components/mod.rs")).unwrap(),
            "// custom comp mod"
        );
        assert!(root.join("src/iu_ui/theme/mod.rs").exists());
    }
}
